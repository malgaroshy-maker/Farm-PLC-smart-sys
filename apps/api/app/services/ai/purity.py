"""Arabic Purity Guard for AI Outputs (Milestone E Round 3).

Checks Arabic text generated by LLMs for:
  - Foreign characters: Hangul (Korean), CJK (Chinese), Kana (Japanese), Cyrillic (Russian)
  - English words (3+ letters) outside an approved technical allow-list.

If impure, triggers retry with secondary model (e.g. free/minimax-m3.1-flash)
and logs `fallback_reason="language_purity"` in the recent AI call log.
"""

import re
from dataclasses import dataclass, field
from typing import Any

# Regex patterns for foreign non-Arabic / non-Latin scripts:
RE_HANGUL = re.compile(r"[\uac00-\ud7af\u1100-\u11ff\u3130-\u318f]")
RE_CJK = re.compile(r"[\u4e00-\u9fff\u3400-\u4dbf\uf900-\ufaff]")
RE_KANA = re.compile(r"[\u3040-\u309f\u30a0-\u30ff]")
RE_CYRILLIC = re.compile(r"[\u0400-\u04ff]")

# Pattern for Latin words of 3 or more letters:
RE_LATIN_WORD = re.compile(r"[a-zA-Z]{3,}")

# Allow-list of legitimate engineering/farm terms, codes, units, and model names:
PURITY_ALLOW_LIST: set[str] = {
    # Alarms and identifiers
    "ALM",
    "PLC",
    "VFD",
    "RTU",
    "HMI",
    "SCADA",
    "MODBUS",
    "RS485",
    "TCP",
    "UDP",
    "API",
    "HTTP",
    "HTTPS",
    "JSON",
    "MQTT",
    "SIM",
    "PID",
    # Engineering units
    "BAR",
    "PSI",
    "M3H",
    "PPM",
    "MIN",
    "SEC",
    "PCT",
    "ET0",
    "KWH",
    # Farm & Zone names / codes
    "ALGAROSHY",
    "FARM",
    "ZONE",
    "PUMP",
    "VALVE",
    "TANK",
    "RUMMAN",
    "ZEITOON",
    "NAKHL",
    "TEEN",
    "HAMDHIYAT",
    "ENAB",
    # Model & provider names
    "APINEX",
    "GEMINI",
    "DEEPSEEK",
    "MUSE",
    "SPARK",
    "LUNA",
    "KIMI",
    "GLM",
    "QWEN",
    "MINIMAX",
    "MIMO",
    "HY4",
    "OPENAI",
    "GOOGLE",
    "CLAUDE",
    "GPT",
    # States and common tokens
    "AUTO",
    "OFF",
    "START",
    "STOP",
}


@dataclass
class PurityReport:
    """Detailed audit of linguistic purity for Arabic outputs."""

    is_pure: bool
    foreign_char_count: int = 0
    english_word_count: int = 0
    violating_words: list[str] = field(default_factory=list)
    total_violations: int = 0


def _is_allowed_latin_word(word: str, extra_allowed: set[str] | None = None) -> bool:
    """Check if a Latin word is on the allowable engineering/code list (or is a real farm name)."""
    w_upper = word.upper()
    if w_upper in PURITY_ALLOW_LIST or (extra_allowed and w_upper in extra_allowed):
        return True
    # Allow ALM-xxx or ZONE_xxx patterns
    if w_upper.startswith("ALM") or w_upper.startswith("ZONE"):
        return True
    return False


def check_arabic_text_purity(
    text: str | None, extra_allowed: set[str] | None = None
) -> PurityReport:
    """Audit a single Arabic text snippet for script mixing and English intrusions."""
    if not text:
        return PurityReport(is_pure=True)

    # 1. Count foreign characters (Hangul, CJK, Kana, Cyrillic)
    hangul = len(RE_HANGUL.findall(text))
    cjk = len(RE_CJK.findall(text))
    kana = len(RE_KANA.findall(text))
    cyrillic = len(RE_CYRILLIC.findall(text))
    foreign_chars = hangul + cjk + kana + cyrillic

    # 2. Count English words of 3+ letters outside allow-list
    latin_words = RE_LATIN_WORD.findall(text)
    violating_words: list[str] = []
    for w in latin_words:
        if not _is_allowed_latin_word(w, extra_allowed):
            violating_words.append(w)

    eng_count = len(violating_words)
    total_violations = foreign_chars + eng_count

    return PurityReport(
        is_pure=(total_violations == 0),
        foreign_char_count=foreign_chars,
        english_word_count=eng_count,
        violating_words=violating_words,
        total_violations=total_violations,
    )


def check_response_purity(response_obj: Any, extra_allowed: set[str] | None = None) -> PurityReport:
    """Audit all Arabic fields of structured response schemas for purity.

    `extra_allowed`: upper-cased Latin words that are real names on this farm (program and
    zone names such as "Live Trio"), which an answer may legitimately quote.
    """
    texts_to_check: list[str] = []

    # AlarmExplanation fields
    if hasattr(response_obj, "title_ar") and response_obj.title_ar:
        texts_to_check.append(response_obj.title_ar)
    if hasattr(response_obj, "diagnosis_ar") and response_obj.diagnosis_ar:
        texts_to_check.append(response_obj.diagnosis_ar)
    if hasattr(response_obj, "probable_causes_ar"):
        texts_to_check.extend(response_obj.probable_causes_ar or [])
    if hasattr(response_obj, "suggested_actions_ar"):
        texts_to_check.extend(response_obj.suggested_actions_ar or [])

    # AdvisorSuggestion fields
    if hasattr(response_obj, "reasoning_ar") and response_obj.reasoning_ar:
        texts_to_check.append(response_obj.reasoning_ar)

    # DailyBriefing fields
    if hasattr(response_obj, "title_ar") and response_obj.title_ar:
        texts_to_check.append(response_obj.title_ar)
    if hasattr(response_obj, "summary_ar") and response_obj.summary_ar:
        texts_to_check.append(response_obj.summary_ar)
    if hasattr(response_obj, "weather_summary_ar") and response_obj.weather_summary_ar:
        texts_to_check.append(response_obj.weather_summary_ar)
    if hasattr(response_obj, "irrigation_overview_ar") and response_obj.irrigation_overview_ar:
        texts_to_check.append(response_obj.irrigation_overview_ar)
    if hasattr(response_obj, "alarms_overview_ar") and response_obj.alarms_overview_ar:
        texts_to_check.append(response_obj.alarms_overview_ar)
    if hasattr(response_obj, "recommendations_ar"):
        texts_to_check.extend(response_obj.recommendations_ar or [])

    # ChatResponse fields
    if hasattr(response_obj, "reply_ar") and response_obj.reply_ar:
        texts_to_check.append(response_obj.reply_ar)

    combined_foreign = 0
    combined_eng = 0
    combined_words: list[str] = []

    for t in texts_to_check:
        rep = check_arabic_text_purity(t, extra_allowed)
        combined_foreign += rep.foreign_char_count
        combined_eng += rep.english_word_count
        combined_words.extend(rep.violating_words)

    total = combined_foreign + combined_eng
    return PurityReport(
        is_pure=(total == 0),
        foreign_char_count=combined_foreign,
        english_word_count=combined_eng,
        violating_words=combined_words,
        total_violations=total,
    )
