export type MsgKey = keyof typeof dict;
/** exposed for tests: every key must exist in both languages */
export const __keys = dict;

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    if (v === 'ar' || v === 'en') return v;
  } catch {
    /* storage unavailable */
  }
  return 'ar';
}

function applyToDocument(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

interface I18nStore {
  lang: Lang;
  setLang: (l: Lang) => void;
  toggle: () => void;
}

export const useI18nStore = create<I18nStore>((set, get) => {
  const lang = initialLang();
  if (typeof document !== 'undefined') applyToDocument(lang);
  return {
    lang,
    setLang(l) {
      try {
        localStorage.setItem(KEY, l);
      } catch {
        /* ignore */
      }
      applyToDocument(l);
      set({ lang: l });
    },
    toggle() {
      get().setLang(get().lang === 'ar' ? 'en' : 'ar');
    },
  };
});

export function translate(lang: Lang, key: MsgKey): string {
  return dict[key]?.[lang] ?? (key as string);
}

/** Hook: `const { t, lang } = useT(); t('nav.alarms')` */
const tCache: Partial<Record<Lang, (key: MsgKey) => string>> = {};

export function useT() {
  const lang = useI18nStore((s) => s.lang);
  // one stable `t` per language: effects that list `t` as a dependency must not
  // re-run on every render (that made the zone drawer refetch its baseline each tick)
  const t = (tCache[lang] ??= (key: MsgKey) => dict[key]?.[lang] ?? (key as string));
  return { lang, t, isRtl: lang === 'ar' };
}

/** Pick the right field from bilingual records (`name` / `name_ar`). */
export function pickName(lang: Lang, en: string | null | undefined, ar: string | null | undefined): string {
  return (lang === 'ar' ? ar || en : en || ar) ?? '';
}

/** Numbers stay Western digits (0-9) in both languages for HMI readability. */
export function fmtNum(n: number | null | undefined, digits = 0): string {
  if (n == null || Number.isNaN(n)) return '--';
  return n.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
}
